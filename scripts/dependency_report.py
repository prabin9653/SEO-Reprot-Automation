"""Read-only dependency report and lock-file writer (R8.4.6).

Compares `requirements.txt` with the packages installed in the CURRENT environment, lists the third-party modules that
`src/seo_report/` imports, computes the transitive closure from installed package metadata, and (with `--write-lock`) writes
`requirements-lock.txt` (runtime) and `requirements-dev-lock.txt` (runtime + test tools) with the exact installed versions.

It never installs, upgrades or removes anything and never touches the network: everything comes from `importlib.metadata`.

    python scripts/dependency_report.py              # report; exit code 1 when something is inconsistent
    python scripts/dependency_report.py --write-lock # also (re)write the two lock files
"""
import ast
import re
import sys
from importlib import metadata as md
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEV_PACKAGES = ("pytest", "matplotlib")  # the test suite; matplotlib only supplies the DejaVu font files for tests


def normalize(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def read_pins(path: Path) -> dict[str, str]:
    pins = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.split("#")[0].strip()
        if line.startswith("-r "):
            continue
        if "==" in line:
            name, version = line.split("==", 1)
            pins[normalize(name)] = version.strip()
    return pins


def third_party_imports(source: Path) -> set[str]:
    """Top-level module names imported under `source` that are neither standard library nor this package."""
    modules = set()
    for path in source.rglob("*.py"):
        for node in ast.walk(ast.parse(path.read_text(encoding="utf-8"))):
            if isinstance(node, ast.Import):
                modules |= {a.name.split(".")[0] for a in node.names}
            elif isinstance(node, ast.ImportFrom) and node.module and node.level == 0:
                modules.add(node.module.split(".")[0])
    return {m for m in modules if m not in sys.stdlib_module_names and m != "seo_report"}


def owners_of(modules) -> dict[str, set[str]]:
    """{module: the installed distributions that provide it}. A namespace such as `google` has several owners."""
    owners = md.packages_distributions()
    return {m: {normalize(d) for d in owners.get(m, ())} for m in modules}


def closure(names) -> dict[str, str | None]:
    """{normalized name: installed version or None} for the names and everything they require (extras not followed)."""
    from packaging.requirements import Requirement
    found: dict[str, str | None] = {}

    def walk(name):
        name = normalize(name)
        if name in found:
            return
        try:
            dist = md.distribution(name)
        except md.PackageNotFoundError:
            found[name] = None
            return
        found[name] = dist.version
        for text in dist.requires or ():
            req = Requirement(text)
            if req.marker is None or req.marker.evaluate({"extra": ""}):
                walk(req.name)

    for name in names:
        walk(name)
    return found


def lock_text(title: str, pins: dict[str, str | None]) -> str:
    lines = [f"# {title}", "# Generated by scripts/dependency_report.py from the installed package metadata of the tested",
             f"# environment (Python {sys.version.split()[0]}, Windows 11). Exact versions; hashes are NOT included (see",
             "# docs/r8/dependency_and_asset_readiness.md). Install with: python -m pip install -r <this file>", ""]
    lines += [f"{name}=={version}" for name, version in sorted(pins.items()) if version]
    return "\n".join(lines) + "\n"


def build_report() -> dict:
    pins = read_pins(ROOT / "requirements.txt")
    owners = owners_of(third_party_imports(ROOT / "src"))
    # a module is covered when ANY of its owners is a direct requirement (`google` is shared by several packages)
    imported = {m: o for m, o in owners.items() if not (o & set(pins))}
    installed = {name: _version(name) for name in pins}
    runtime = closure(pins)
    dev = closure(list(pins) + list(DEV_PACKAGES))
    return {"pins": pins, "unowned": sorted(imported), "mismatched": {n: (pins[n], v) for n, v in installed.items() if v != pins[n]},
            "imported_not_pinned": sorted(d for o in imported.values() for d in o) or sorted(imported), "runtime": runtime, "dev": dev,
            "missing": sorted(n for n, v in dev.items() if v is None)}


def _version(name):
    try:
        return md.version(name)
    except md.PackageNotFoundError:
        return None


def main(argv=None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    report = build_report()
    print(f"python {sys.version.split()[0]}; pinned {len(report['pins'])}; runtime closure {len(report['runtime'])}; "
          f"with test tools {len(report['dev'])}")
    problems = 0
    for name, (wanted, got) in report["mismatched"].items():
        print(f"MISMATCH {name}: requirements.txt {wanted}, installed {got}")
        problems += 1
    for name in report["imported_not_pinned"]:
        print(f"NOT PINNED (imported by src/): {name}")
        problems += 1
    for name in report["missing"]:
        print(f"NOT INSTALLED: {name}")
        problems += 1
    if "--write-lock" in args:
        if problems:
            print("lock files not written: fix the problems above first")
            return 1
        (ROOT / "requirements-lock.txt").write_text(lock_text("Runtime lock: every package the runner needs", report["runtime"]),
                                                    encoding="utf-8", newline="\n")
        (ROOT / "requirements-dev-lock.txt").write_text(
            lock_text("Runtime + test lock: everything needed to run the test suite", report["dev"]), encoding="utf-8", newline="\n")
        print("wrote requirements-lock.txt and requirements-dev-lock.txt")
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
